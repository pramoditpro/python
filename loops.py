####### for loop
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)

for i in range(5):
    print(i)

for i in range(102, 110, 2):
    print(i)

for i in range(5 , 15):
    if i == 7:
        continue
    if i == 13:
        break
    print(i)    

